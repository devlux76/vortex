#!/bin/sh
# Regenerate src/core/proto from proto/*.proto. Run from the project root: bun run proto
set -e
node_modules/.bin/protons --strict -o src/core/proto proto/*.proto
for file in src/core/proto/*.ts; do
  # The generated code uses namespaces, which erasableSyntaxOnly forbids in hand-written code.
  sed -i '1i // @ts-nocheck -- generated by protons from proto/; do not edit. Regenerate with: bun run proto' "$file"
done
